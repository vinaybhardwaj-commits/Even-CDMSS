#!/usr/bin/env node
// scripts/icd-master-gen.mjs — snapshots the db13 `icd_code` master into the committed,
// generated artifact lib/member-state/icd-master.generated.ts (ICD Master Slice 1).
//
//   node --env-file=.env.local --import tsx scripts/icd-master-gen.mjs 2026-07-13
//   (or: npm run icd:master -- 2026-07-13)
//
// GENERATED-NOT-AUTHORED, with one honest caveat: this artifact snapshots a DB table, and CI
// has no db13 credentials, so the staleness gate CANNOT regenerate it — refresh is a manual
// rerun of this script. New codes appearing in db13 after the snapshot degrade gracefully to
// the neutral "(unmapped ICD-10 code)" fallback in the resolver — never a wrong label.
//
// DETERMINISM: rows are keyset-paginated in code order, keys sorted, and the snapshot date is
// a REQUIRED CLI arg — no Date.now() reaches the generated content. Same table state + same
// date arg → byte-identical output.
//
// READ-ONLY against db13. The Metabase /api/dataset endpoint caps a query at ~2000 rows, so
// the full 98k-row master is fetched in ORDER BY code batches with a `> cursor` predicate.

import { writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { metabaseQuery } from '../lib/metabase.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = 'lib/member-state/icd-master.generated.ts';
const BATCH = 1900; // safely under Metabase's row cap

const snapshotDate = process.argv[2];
if (!/^\d{4}-\d{2}-\d{2}$/.test(snapshotDate ?? '')) {
  console.error('usage: icd-master-gen.mjs <YYYY-MM-DD>   (the snapshot date — passed in, never Date.now())');
  process.exit(1);
}

// codes are [A-Z0-9.] after upper(trim()); the cursor is interpolated, so hard-verify it.
const safeCursor = (c) => /^[A-Z0-9.]+$/.test(c);

async function fetchAll() {
  const rows = [];
  let cursor = '';
  for (;;) {
    const pred = cursor ? ` AND upper(trim(icd_code)) > '${cursor}'` : '';
    const batch = await metabaseQuery(
      `SELECT upper(trim(icd_code)) AS code, short_desc, duration, is_high_risk
         FROM icd_code
        WHERE coalesce(icd_code,'') <> '' AND coalesce(short_desc,'') <> ''${pred}
        ORDER BY 1
        LIMIT ${BATCH}`,
    );
    rows.push(...batch);
    process.stdout.write(`\r  fetched ${rows.length} rows…`);
    if (batch.length < BATCH) break;
    cursor = String(batch[batch.length - 1].code);
    if (!safeCursor(cursor)) throw new Error(`unsafe cursor value: ${JSON.stringify(cursor)}`);
  }
  console.log('');
  return rows;
}

const main = async () => {
  console.log('icd-master-gen — snapshotting db13 icd_code (read-only)…');
  const rows = await fetchAll();

  // Codes are verified unique in the master; dedupe defensively anyway (first non-empty desc wins).
  const labels = new Map();
  const meta = new Map();
  let collisions = 0;
  for (const r of rows) {
    const code = String(r.code);
    const desc = String(r.short_desc ?? '').trim();
    if (!desc) continue;
    if (labels.has(code)) {
      collisions++;
      console.warn(`  collision (kept first): ${code} — dropped "${desc.slice(0, 60)}"`);
      continue;
    }
    labels.set(code, desc);
    meta.set(code, [String(r.duration ?? ''), r.is_high_risk === true ? 1 : 0]);
  }
  const codes = [...labels.keys()].sort();
  console.log(`  ${codes.length} unique codes (${collisions} collisions dropped).`);

  const labelLines = codes.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(labels.get(c))},`);
  const metaLines = codes.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(meta.get(c))},`);

  const src = `// GENERATED by icd-master-gen.mjs from db13 icd_code · ${codes.length} codes · snapshot ${snapshotDate}.
// Do not edit by hand. Refresh: \`npm run icd:master -- <YYYY-MM-DD>\` (manual, needs db13 creds
// via --env-file=.env.local — CI cannot regenerate this artifact and does not try; the honest
// drift story is: codes added to db13 after the snapshot fall back to the neutral
// "(unmapped ICD-10 code)" label in icd-labels.ts — never a wrong label).
//
// SERVER-SIDE ONLY (~this file is multi-MB): imported by lib/member-state/icd-labels.ts, which
// only server code reaches. Never import from a 'use client' component.

export const ICD_MASTER_VERSION = 'icd-master/1.0';

/** code → short_desc, verbatim from the master (sentence-cased). Keys are dotted, upper-case. */
export const ICD_MASTER: Record<string, string> = {
${labelLines.join('\n')}
};

/** SLICE-2 PAYLOAD — not consumed by any live path yet. code → [duration, isHighRisk];
 *  duration ∈ 'ACUTE' | 'SUB_ACUTE' | 'CHRONIC'. Shipped with the snapshot so chronicity/
 *  complexity adoption (its own PRD: golden A/B + clinician ratification) needs no re-pull. */
export const ICD_META: Record<string, [string, 0 | 1]> = {
${metaLines.join('\n')}
};
`;
  writeFileSync(join(ROOT, OUT_PATH), src);
  console.log(`  wrote ${OUT_PATH} (${(src.length / 1024 / 1024).toFixed(1)} MB).`);
};

main().catch((e) => { console.error(`FATAL: ${e.message}`); process.exit(1); });
